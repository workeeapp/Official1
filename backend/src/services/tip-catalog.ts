export function topicFromListType(listType: string | null | undefined): TipTopic | null {
  const t = (listType ?? "").trim();
  if (t === "shopping") return "shopping";
  if (t === "tasks") return "tasks";
  if (t === "custom") return "custom";
  if (t === "filing") return "filing";
  if (t === "reminders") return "reminders";
  if (t === "contacts") return "directory";
  return null;
}

export function areaFromTopic(topic: TipTopic): TipTriggerArea {
  if (topic === "filing") return "filing";
  if (topic === "reminders") return "reminders";
  if (topic === "directory" || topic === "guest") return "directory";
  return "lists";
}
